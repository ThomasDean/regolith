// Bundles each game's online referee and rules engine into one file per Supabase Edge
// Function, so Deno needs no imports or build step of its own.
import { build } from 'esbuild';

const FUNCTIONS = [
  { entry: 'server/edge.ts', out: 'supabase/functions/regolith-play/index.js' },
  { entry: 'server/fathom-edge.ts', out: 'supabase/functions/fathom-play/index.js' },
];

for (const f of FUNCTIONS) {
  await build({
    entryPoints: [f.entry],
    outfile: f.out,
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    banner: { js: `// Generated by scripts/build-edge.mjs from ${f.entry} and src/. Do not edit.` },
    logLevel: 'info',
  });
}
