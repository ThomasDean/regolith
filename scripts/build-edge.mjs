// Bundles the online referee and the rules engine into one file for the Supabase Edge
// Function, so Deno needs no imports or build step of its own.
import { build } from 'esbuild';

await build({
  entryPoints: ['server/edge.ts'],
  outfile: 'supabase/functions/regolith-play/index.js',
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-edge.mjs from server/edge.ts and src/. Do not edit.' },
  logLevel: 'info',
});
